import type { ArchitectureResult } from "./types";

export function toMarkdown(result: ArchitectureResult, source: string): string {
  const arch = result.applicationArchitecture;
  const lines: string[] = [
    `# ${result.title}`,
    "",
    `_Generated by ArcGate AI with OpenAI (${source})._`,
    "",
    "## Proposed solution",
    "",
    result.proposedSolution,
    "",
    "## Functional requirements",
    "",
    ...result.functionalRequirements.flatMap((fr) => [
      `### ${fr.id} — ${fr.title} (${fr.priority})`,
      "",
      fr.description,
      "",
    ]),
    "## Non-functional requirements",
    "",
    ...result.nonFunctionalRequirements.flatMap((nfr) => [
      `### ${nfr.id} — ${nfr.category}`,
      "",
      nfr.requirement,
      "",
      `Target: ${nfr.target}`,
      "",
    ]),
    "## Application architecture",
    "",
    `Style: ${arch.style}${arch.styleId ? ` (${arch.styleId})` : ""}`,
    "",
    arch.styleRationale ? `Why this style: ${arch.styleRationale}` : "",
    "",
    arch.overview,
    "",
    arch.dataFlow,
    "",
    "### Application layers",
    ...arch.layers.flatMap((layer) => [
      `#### ${layer.name}`,
      "",
      layer.responsibilities,
      "",
      layer.components.map((c) => `\`${c}\``).join(" · "),
      "",
    ]),
    "### Application modules",
    ...arch.modules.flatMap((module) => [
      `- **${module.name}** (${module.layer}) — ${module.responsibilities}`,
    ]),
    "",
    "### Technology choices",
    ...arch.techStack.flatMap((stack) => [
      `- **${stack.layer}:** ${stack.choices.join(", ")} — ${stack.why}`,
    ]),
    "",
    "### Integration points",
    ...arch.integrationPoints.map((item) => `- ${item}`),
    "",
    "```mermaid",
    arch.mermaid,
    "```",
    "",
    "## Assumptions",
    "",
    ...result.assumptions.map((item) => `- ${item}`),
    "",
  ];

  return lines.join("\n");
}
